def palavra_do_dia(data: date, segredo: str) -> str:
    mensagem = f"palavra-do-dia:{data.isoformat()}".encode()
    resumo = hmac.new(segredo.encode(), mensagem, hashlib.sha256).digest()
    indice = int.from_bytes(resumo[:8], "big") % len(PALAVRAS)
    return PALAVRAS[indice]
